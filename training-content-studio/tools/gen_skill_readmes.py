def sections(text):
    out, cur = {}, None
    for line in text.split('\n'):
        m = re.match(r'^## (.+)', line)
        if m:
            cur = m.group(1).split(' (')[0].split(' —')[0].strip()
            out[cur] = []
        elif cur:
            out[cur].append(line)
    return {k: '\n'.join(v).strip() for k, v in out.items()}


def tree(d):
    lines = [f'{d.name}/']
    for p in sorted(d.rglob('*')):
        rel = p.relative_to(d)
        if any(x in ('tests', '__pycache__') for x in rel.parts) or p.name in ('README.md', '.DS_Store') or len(rel.parts) > 2:
            continue
        lines.append('  ' * len(rel.parts) + rel.parts[-1] + ('/' if p.is_dir() else ''))
    return '\n'.join(lines[:40])


def main(force):
    for sk in sorted((ROOT / 'skills').glob('*/SKILL.md')):
        d = sk.parent
        out = d / 'README.md'
        if out.exists() and not force and MARK not in out.read_text():
            continue
        text = sk.read_text()
        fm = yaml.safe_load(re.match(r'^---\n(.*?)\n---\n', text, re.S).group(1))
        name, desc = fm['name'], fm['description']
        sec = sections(text)
        sents = re.split(r'(?<=[.!?])\s+', desc)
        what = ' '.join(s for s in sents if not re.match(r'\s*(Use|Not|Do NOT)\b', s, re.I))
        use = [s for s in sents if re.match(r'\s*Use\b', s)]
        notf = [s for s in sents if re.match(r'\s*(Not|Do NOT)\b', s, re.I)]
        ex = EX.get(name, [])
        body = [MARK, f'# {name}', '', what, '',
                'Part of the **[Training Content Studio](../training-content-studio/README.md)** plugin.', '',
                "## What it's for", sec.get('Purpose', what), '',
                '## When to use it'] + [f'- {s}' for s in use] + [f"- **Not for:** {re.sub(r'^(Not (for|when)|Do NOT( use)?( it)?( for| when| to)?)\s*', '', s, flags=re.I)}" for s in notf] + ['',
                '## Install', '```bash',
                '# whole plugin (recommended: scripts use the shared schemas/, kit/, assets/)',
                f'git clone https://github.com/{REPO} && claude --plugin-dir tamer-skills/training-content-studio',
                '# this skill only (instructions only; its scripts need the plugin root)',
                f'npx skills add {REPO} --skill {name} --agent claude-code', '```',
                'Prerequisites: Python 3.12 venv with `tools/requirements.txt` (plugin root); keys via env or `TCS_ENV_FILE` '
                '(`OPENAI_API_KEY` for narration/transcription, `PEXELS_API_KEY` optional); Node 18+ and ffmpeg for video renders.', '',
                '## How to use', '```', f'/{name} <request or file>', '```',
                '**Inputs**', '', sec.get('Inputs', '—'), '', '**Outputs**', '', sec.get('Outputs', '—'), '',
                '## Examples']
        for i, (title, prompt, result) in enumerate(ex, 1):
            body += [f'**Example {i}: {title}**', f'Prompt: `{prompt}`', f'Result: {result}', '']
        body += ['## Layout', '```', tree(d), '```', '',
                 '## Dependencies',
                 '- Contracts in the plugin `schemas/` (sources, curriculum, storyboard, quiz, grounding_report, decisions, run_state).',
                 '- Related skills: see the plugin README catalog.', '',
                 '## Changelog', '- 2026-11-17 — initial version (training-content-studio 1.0.0)', '']
        out.write_text('\n'.join(body))
        print('wrote', out.relative_to(ROOT))


