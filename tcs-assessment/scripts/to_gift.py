#!/usr/bin/env python3
"""Export quiz.json to Moodle GIFT (also imported by many LMSs).

Usage: to_gift.py <quiz.json> [--out quiz.gift.txt] [--lang ar]   (--lang ar uses stem_ar/text_ar when present)
Mapping: mcq/scenario -> single answer (=/~, #feedback); multi -> weighted %; true_false -> {T}/{F}; matching -> {=a -> b};
ordering -> matching to positions "1st..nth"; flashcard -> description-only item (no grading).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

SPECIAL = "~=#{}:\\"


def esc(t: str) -> str:
    return "".join("\\" + c if c in SPECIAL else c for c in " ".join(str(t).split()))


def txt(obj: dict, key: str, ar: bool) -> str:
    return obj.get(f"{key}_ar") if ar and obj.get(f"{key}_ar") else obj.get(key, "")


def item_gift(it: dict, ar: bool) -> str:
    stem = txt(it, "stem", ar)
    if it.get("scenario"):
        stem = f"{it['scenario']}\n\n{stem}"
    title = f"::{esc(it['id'])} [{it['objective_id']}]::"
    opts = it.get("options", [])
    t = it["type"]
    fb = lambda o: f" #{esc(o['feedback'])}" if o.get("feedback") else ""  # noqa: E731
    gen = f"####{esc(it['explanation'])}" if it.get("explanation") else ""
    if t in ("mcq", "scenario"):
        body = "\n".join(f"  {'=' if o.get('correct') else '~'}{esc(txt(o, 'text', ar))}{fb(o)}" for o in opts)
        return f"{title}{esc(stem)} {{\n{body}\n{gen}}}"
    if t == "multi":
        n_ok = sum(1 for o in opts if o.get("correct")) or 1
        n_bad = (len(opts) - n_ok) or 1
        w_ok, w_bad = round(100 / n_ok, 5), -round(100 / n_bad, 5)
        body = "\n".join(f"  ~%{w_ok if o.get('correct') else w_bad}%{esc(txt(o, 'text', ar))}{fb(o)}" for o in opts)
        return f"{title}{esc(stem)} {{\n{body}\n{gen}}}"
    if t == "true_false":
        ok = next((o for o in opts if o.get("correct")), {})
        is_true = str(ok.get("text", "")).strip().lower() in ("true", "صح", "صحيح", "t", "yes")
        bad = next((o for o in opts if not o.get("correct")), {})
        return f"{title}{esc(stem)} {{{'TRUE' if is_true else 'FALSE'}{fb(bad)}{fb(ok)}{gen}}}"
    if t == "matching":
        body = "\n".join(f"  ={esc(txt(o, 'text', ar))} -> {esc(o['match'])}" for o in opts)
        return f"{title}{esc(stem)} {{\n{body}\n}}"
    if t == "ordering":
        names = ["1st", "2nd", "3rd"] + [f"{i}th" for i in range(4, 21)]
        body = "\n".join(f"  ={esc(txt(o, 'text', ar))} -> {names[o['order'] - 1]}"
                         for o in sorted(opts, key=lambda o: o["order"]))
        return f"{title}{esc(stem)} (put in order) {{\n{body}\n}}"
    if t == "flashcard":
        return f"{title}{esc(stem)} — {esc(it.get('back', ''))}"
    return ""


def to_gift(q: dict, ar: bool = False) -> str:
    head = f"// {q['quiz_id']} · {q['course_id']} · {q.get('lesson_id', '')} · {q['language']} · generated by tcs-assessment\n"
    head += f"$CATEGORY: $course$/{q['course_id']}/{q.get('lesson_id', q['quiz_id'])}\n\n"
    return head + "\n\n".join(x for x in (item_gift(i, ar) for i in q["items"]) if x) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("quiz")
    ap.add_argument("--out")
    ap.add_argument("--lang", choices=["src", "ar"], default="src")
    a = ap.parse_args(argv)
    q = json.loads(Path(a.quiz).read_text(encoding="utf-8"))
    g = to_gift(q, a.lang == "ar")
    out = Path(a.out) if a.out else Path(a.quiz).with_suffix(".gift.txt")
    out.write_text(g, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
