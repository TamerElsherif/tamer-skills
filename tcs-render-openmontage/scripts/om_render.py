"""Render a prepared TCS run_dir through the user's local OpenMontage install (video_compose atelier path).

usage: .venv/bin/python skills/tcs-render-openmontage/scripts/om_render.py <run_dir> [--draft] [--slug SLUG]
       (or a storyboard / runs/<id> dir via:  skills/tcs-render-remotion/scripts/render_lesson.py <src> --engine openmontage)

Needs OPENMONTAGE_ROOT (alias OPENMONTAGE_DIR; default ~/OpenMontage) with .venv and remotion-composer/node_modules.
Steps: init_project → stage composition (kit src + index.tsx + timeline.ts) under OPENMONTAGE_ROOT/projects/<slug>/composition/
→ write artifacts (edit_decisions.json, decision_log.json) → VideoCompose.execute(operation=render, composition_mode=atelier)
with OpenMontage's own venv → loudnorm -16 LUFS → <run_dir>/renders/<lesson_id>_<tag>_om.mp4 (+ copy in projects/<slug>/renders/).
OpenMontage source is never modified; only a project folder is written.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tcs-render-remotion" / "scripts"))
from _common import KIT_DIR, aspect_tag, comp_id, has_audio, probe_duration, write_json  # noqa: E402


def om_root() -> Path:
    r = os.environ.get("OPENMONTAGE_ROOT") or os.environ.get("OPENMONTAGE_DIR") or str(Path.home() / "OpenMontage")
    return Path(r).expanduser().resolve()


DRIVER = r'''
import json, sys
sys.path.insert(0, ".")
from tools.video.video_compose import VideoCompose
ed, out = json.loads(sys.argv[1]), sys.argv[2]
r = VideoCompose().execute({"operation": "render", "edit_decisions": ed, "output_path": out})
rev = (r.data or {}).get("final_review", {}) if r.data else {}
print("OMRESULT " + json.dumps({"success": r.success, "error": r.error, "review": rev.get("status"), "issues": rev.get("issues_found")}, default=str))
'''

INIT = r'''
import sys, json
sys.path.insert(0, ".")
from lib.checkpoint import init_project
p = init_project(sys.argv[1], title=sys.argv[2], pipeline_type="animated-explainer")
print(p)
'''


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run_dir")
    ap.add_argument("--draft", action="store_true")
    ap.add_argument("--slug")
    a = ap.parse_args()
    run_dir = Path(a.run_dir).resolve()
    om = om_root()
    py = om / ".venv" / "bin" / "python"
    if not py.exists() or not (om / "remotion-composer" / "node_modules").exists():
        sys.exit(f"OpenMontage not usable at {om} (need .venv and remotion-composer/node_modules); set OPENMONTAGE_ROOT")
    tl = json.loads((run_dir / "timeline.json").read_text(encoding="utf-8"))["tl"]
    lesson = tl["lesson_id"]
    slug = a.slug or comp_id(f"tcs-{lesson}").lower()
    cid = comp_id(lesson)
    tag = aspect_tag(tl.get("aspect", "16:9"))

    # 1. project marker (Backlot board)
    r = subprocess.run([str(py), "-c", INIT, slug, f"TCS · {tl.get('title', lesson)}"], cwd=om, capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"init_project failed: {r.stderr[-800:]}")
    proj = Path(r.stdout.strip().splitlines()[-1])

    # 2. composition (atelier stages only .ts/.tsx/.js/.css → timeline emitted as a .ts module)
    comp = proj / "composition"
    if comp.exists():
        shutil.rmtree(comp)
    shutil.copytree(KIT_DIR / "src", comp / "kit", ignore=shutil.ignore_patterns("index.ts"))
    shutil.copy2(run_dir / "timeline.ts", comp / "timeline.ts")
    (comp / "index.tsx").write_text(
        "// AUTO-GENERATED by training-content-studio tcs-render-openmontage — renders one TCS lesson timeline.\n"
        "import { registerRoot } from 'remotion';\nimport { makeFixedRoot } from './kit/Root';\nimport { Timeline } from './kit/core/types';\n"
        f"import T from './timeline';\n\nregisterRoot(makeFixedRoot(T as unknown as Timeline, '{cid}'));\n", encoding="utf-8")
    (comp / "art-direction.md").write_text(
        "# Art direction (Training Content Studio kit)\n\nData-driven training lesson rendered from storyboard.json by the TCS template kit: "
        f"theme preset `{(tl.get('theme') or {}).get('preset', 'neutral')}`, navy/blue→cyan palette with one attention colour, flat-vector personas, "
        "cue-synced reveals. Templates are the plugin's own (no OpenMontage stock components).\n", encoding="utf-8")
    # public dir: link the prepared assets (audio, broll, images, music, sfx)
    pub = proj / "assets" / "public"
    if pub.is_symlink() or pub.exists():
        pub.unlink() if pub.is_symlink() else shutil.rmtree(pub)
    pub.symlink_to(run_dir / "public", target_is_directory=True)

    # 3. artifacts
    art = proj / "artifacts"
    raw = proj / "renders" / f"{lesson}_{tag}{'_draft' if a.draft else ''}.raw.mp4"
    ed = {"version": "1.0", "cuts": [], "render_runtime": "remotion", "composition_mode": "atelier", "renderer_family": "bespoke",
          "bespoke": {"entry": str(comp / "index.tsx"), "composition_id": cid, "public_dir": str(pub.resolve()),
                      "art_direction": str(comp / "art-direction.md"), "crf": 28 if a.draft else 19, "concurrency": max(2, (os.cpu_count() or 4) // 2),
                      **({"scale": 0.5} if a.draft else {})},
          "metadata": {"source": "training-content-studio", "lesson_id": lesson, "run_dir": str(run_dir), "aspect": tl.get("aspect")}}
    write_json(art / "edit_decisions.json", ed)
    write_json(proj / "decision_log.json", {"version": "1.0", "project_id": slug, "decisions": [
        {"decision_id": "tcs-001", "stage": "compose", "category": "render_runtime_selection", "subject": "Render runtime for TCS lesson",
         "options_considered": [{"option_id": "remotion", "label": "Remotion (atelier)", "score": 1.0, "reason": "TCS kit is a Remotion template dispatcher"},
                                {"option_id": "hyperframes", "label": "HyperFrames", "score": 0.2, "reason": "kit not ported", "rejected_because": "no HTML kit"}],
         "selected": "remotion", "reason": "storyboard.json renders through the TCS kit with no hand-written scenes"},
        {"decision_id": "tcs-002", "stage": "compose", "category": "composition_mode", "subject": "Composition mode",
         "options_considered": [{"option_id": "atelier", "label": "atelier (project-local entry)", "score": 1.0, "reason": "kit + timeline staged as project-local source"}],
         "selected": "atelier", "reason": "project-local Remotion entry via video_compose._render_via_atelier"}]})

    # 4. render with OpenMontage's own venv
    raw.parent.mkdir(parents=True, exist_ok=True)
    r = subprocess.run([str(py), "-c", DRIVER, json.dumps(ed), str(raw)], cwd=om, capture_output=True, text=True)
    res = next((json.loads(l[9:]) for l in r.stdout.splitlines() if l.startswith("OMRESULT ")), None)
    if not res or not raw.exists():
        sys.exit(f"OpenMontage render failed: {(res or {}).get('error') or r.stderr[-1500:]}")
    out_dir = run_dir / "renders"
    out_dir.mkdir(parents=True, exist_ok=True)
    final = out_dir / f"{lesson}_{tag}{'_draft' if a.draft else ''}_om.mp4"
    if has_audio(raw):
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(raw), "-c:v", "copy", "-af", "loudnorm=I=-16:TP=-1.5:LRA=11", "-ar", "48000",
                        "-c:a", "aac", "-b:a", "192k", "-movflags", "+faststart", str(final)], check=True)
    else:
        shutil.copy2(raw, final)
    raw.unlink()
    shutil.copy2(final, proj / "renders" / final.name)
    info = {"lesson_id": lesson, "output": str(final), "openmontage_project": str(proj), "aspect": tl.get("aspect"),
            "duration_s": round(probe_duration(final), 2), "audio": has_audio(final), "om_review": res.get("review"), "om_issues": res.get("issues"), "draft": a.draft}
    write_json(out_dir / f"{final.stem}.json", info)
    write_json(art / "render_report.json", info)
    print(json.dumps(info, indent=1, ensure_ascii=False))


if __name__ == "__main__":
    main()
